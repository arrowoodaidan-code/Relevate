const results: string[] = [];
async function run(name: string, payload: Record<string, unknown>, expectPng: boolean) {
  const check = validateRenderRequest(payload);
  if (!check.ok) {
    results.push(`❌ ${name}: validateRenderRequest REJECTED — ${check.error}`);
    return;
  }
  try {
    const dataUrl = await renderMarketingPng(check.data);
    const png = Buffer.from(dataUrl.split(",")[1], "base64");
    await writeFile(`${dir}/${name}.png`, png);
    results.push(`✅ ${name}: validated + rendered (${(png.length / 1024).toFixed(0)} KB, ${expectPng ? "PNG" : "unexpected"})`);
  } catch (err) {
    results.push(`❌ ${name}: render threw — ${err instanceof Error ? err.message : String(err)}`);
  }
}

