function samplePixel(dataUrl: string, width: number, height: number, fx: number, fy: number): [number, number, number] {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"><image href="${dataUrl}" x="0" y="0" width="${width}" height="${height}"/></svg>`;
  const rendered = new Resvg(svg).render();
  const px = rendered.pixels;
  const x = Math.max(0, Math.min(width - 1, Math.round(fx * width)));
  const y = Math.max(0, Math.min(height - 1, Math.round(fy * height)));
  const i = (y * width + x) * 4;
  return [px[i], px[i + 1], px[i + 2]];
}
// min/max luminance over an entire region box of the rendered output
function boxLum(dataUrl: string, width: number, height: number, rx: number, ry: number, rw: number, rh: number): { min: number; max: number } {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"><image href="${dataUrl}" x="0" y="0" width="${width}" height="${height}"/></svg>`;
  const px = new Resvg(svg).render().pixels;
  const x0 = Math.max(0, Math.round(rx * width)), y0 = Math.max(0, Math.round(ry * height));
  const x1 = Math.min(width - 1, Math.round((rx + rw) * width)), y1 = Math.min(height - 1, Math.round((ry + rh) * height));
  let min = 255, max = 0;
  for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) {
    const i = (y * width + x) * 4;
    const l = 0.2126 * px[i] + 0.7152 * px[i + 1] + 0.0722 * px[i + 2];
    if (l < min) min = l;
    if (l > max) max = l;
  }
  return { min, max };
}
const lum = (c: [number, number, number]) => 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
const maxDelta = (a: [number, number, number], b: [number, number, number]) => Math.max(Math.abs(a[0] - b[0]), Math.abs(a[1] - b[1]), Math.abs(a[2] - b[2]));
const hexRgb = (hex: string): [number, number, number] => [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16)];

